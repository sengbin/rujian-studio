/**
 * 生成 count 个以逗号分隔的占位符，如 3 个为 `?, ?, ?`；count 为 0 时返回空串。
 * @param count 参数个数。
 */
export function placeholders(count: number): string {
  return Array.from({ length: count }, () => '?').join(', ');
}

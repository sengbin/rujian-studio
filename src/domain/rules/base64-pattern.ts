/** Base64 内容的正则片段：字符集加末尾最多两个填充符，可嵌入更大的正则。 */
export const BASE64_BODY = '[A-Za-z0-9+/]*={0,2}';

/** 整个字符串都是 Base64 内容。 */
export const BASE64_PATTERN = new RegExp(`^${BASE64_BODY}$`);

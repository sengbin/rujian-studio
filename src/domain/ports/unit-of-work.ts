// ------------------------------------------------------------------------

/** 工作单元：在一个事务中执行同步操作。 */
export interface UnitOfWork {
  /**
   * 在一个事务中执行操作：成功则提交并返回结果，抛出异常则撤销操作中的全部写入并重新抛出。
   * @param work 需要原子执行的同步操作，不能返回 Promise。
   */
  runInTransaction<T>(work: () => T): T;
}
